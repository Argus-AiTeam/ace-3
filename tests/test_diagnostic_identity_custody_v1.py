def origins_for(case):
    directory, proposal, catalog, _ = case
    declaration = {
        "schema_version": 1, "kind": "diagnostic_identity_declaration",
        "diagnostic_identity": proposal["identity"],
        **{field: proposal[field] for field in ("source_roles", "source_snapshots", "launch")}}
    terminals = {
        "schema_version": 1, "kind": "diagnostic_terminal_declarations",
        "scoped_missions": [lane["mission_id"] for lane in catalog["lanes"]],
        "lanes": [{key: value for key, value in lane.items() if key != "identity_paths"}
                  for lane in catalog["lanes"]]}
    return {"proposal": prior.put(directory, "declaration.json", declaration),
            "terminals": prior.put(directory, "terminal-declarations.json", terminals)}


def produce(case, origins=None):
    if origins is None:
        origins = origins_for(case)
    attempt = case[0] / "custody"
    reservation = capture.reserve_authentication_attempt(attempt)
    result = custody.emit_custody(origins, case[3], attempt, reservation)
    assert result["dispatch_authorized"] is False
    assert result["authority_root"] is result["scientific_or_admission_claim"] is False
    assert all(result[key] == 0 for key in
               ("scientific_invocations", "producer_invocations", "service_invocations"))
    return result, origins


