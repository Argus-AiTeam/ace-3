def change_capture(case, mutation):
    """Build new synthetic retained bytes/review links; never edit a real capture."""
    lane = case[2]["lanes"][0]
    receipt = deepcopy(capture.retained_document(lane["capture"]["receipt"]))
    row = receipt["results"][0]
    data = [Path(pin["path"]).read_bytes() for pin in row["files"]]
    if mutation == "missing_identity":
        data[3] = capture.encoded({"task_name": "synthetic-closed", "status": "done",
                                  "narrative": "identity cannot be reconstructed"})
    elif mutation == "duplicate_identity":
        data[3] = b'{"diagnostic_identity":{},"diagnostic_identity":{}}\n'
    elif mutation == "argv":
        data[1] = capture.encoded(row["argv"] + ["--changed"])
    elif mutation == "environment":
        environment = capture.decode_retained(data[2])
        environment["environment"]["A"] = "changed"
        data[2] = capture.encoded(environment)
    elif mutation == "timeout":
        row["timed_out"] = True
    elif mutation == "exit":
        row["exit_status"] = 9
    if mutation in {"missing_identity", "duplicate_identity"}:
        data[5] = (b"COMMAND\n" + data[0] + b"ENVIRONMENT\n" + data[2] + b"\nSTDOUT\n"
                   + data[3] + b"\nSTDERR\n" + data[4] + b"\nEXIT_STATUS=0\nTIMED_OUT=False\n")
    elif mutation == "framing":
        data[5] += b"extra unframed bytes"
    directory = case[0] / "mutant-retained"
    directory.mkdir()
    row["files"] = [prior.put(directory, row["label"] + suffix, value)
                    for suffix, value in zip(capture.SUFFIXES, data, strict=True)]
    if mutation == "member_link":
        row["files"][3], row["files"][4] = row["files"][4], row["files"][3]
    receipt_pin = prior.put(directory, "capture.json", receipt)
    lane["capture"] = {**lane["capture"], "directory": str(directory), "receipt": receipt_pin}
    native = lane["native"]["pin"]
    checkpoint = prior.put(directory, "checkpoint.txt", (
        f"capture.json {receipt_pin['sha256']}\n"
        f"{Path(native['path']).name} {native['sha256']}\n").encode())
    review = capture.retained_document(lane["review"])
    review["checkpoint"] = {"path": checkpoint["path"]}
    review_pin = prior.put(directory, "review.json", review)
    latest = prior.put(directory, "latest.json", {
        "kind": "handoff_ref", "handoff": {"path": review_pin["path"]}})
    lane.update(latest=latest, review=review_pin, checkpoint=checkpoint)


