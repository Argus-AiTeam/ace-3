def retained_validation(attempt):
    positive = prior._retained_capture_validation(attempt)
    prior.put(attempt, "retained.command-environment.json", {
        "launch": positive["identity"], "commands": positive["run_expectation"]})
    prior.put(attempt, "retained.source-role.receipt.json", {
        "roles": positive["source_roles"], "snapshots": positive["generation_snapshots"],
        "review_links": positive["review"], "latest": positive["latest"]})
    run = capture.retained_document(positive["run"])
    rows = [row for row in run["results"] if row["label"] == "check"]
    if len(rows) != 1:
        raise capture.UnavailableBinding("missing retained check payload in 92c capture receipt")
    payload_pin = rows[0]["files"][3]
    review_pin = positive["review"]["review"]
    historical = {}
    for name, pin, field in (("proposal", payload_pin, "diagnostic_identity"),
                             ("catalog", review_pin, "terminal_catalog")):
        document = capture.retained_document(pin)
        try:
            gate._at(document, [field], pin["path"])
        except capture.UnavailableBinding as error:
            receipt = {"status": "UNKNOWN", "origin": pin, "field": field,
                       "unavailable_binding": str(error), "reconstructed": False}
        else:
            raise RuntimeError(f"historical fixture unexpectedly contains {field}")
        historical[name] = prior.put(attempt, f"retained.{name}.receipt.json", receipt)
    synthetic = list((attempt / "pytest-tmp").glob(
        "test_emits_schema_one[0-9]*/custody/custody-receipt.json"))
    if len(synthetic) != 1:
        raise RuntimeError("expected one retained synthetic positive custody receipt")
    prior.put(attempt, "proposal-catalog.receipts.json", {
        "synthetic_custody": capture.binding(synthetic[0]), "historical": historical,
        "independent_review": "REQUIRED", "authority_root": False})
    prior.put(attempt, "retained-integration.results.json", {
        "status": "PASS", "capture_authenticated": True,
        "historical_identity_status": "UNKNOWN", "historical_catalog_status": "UNKNOWN",
        "historical_capture": positive["capture"], "historical_run": positive["run"],
        "reclassification_performed": False, "scientific_or_admission_claim": False})


def stage11_retained_validation(attempt, *, declaration_files=()):
    positive = prior._retained_capture_validation(attempt)
    prior.put(attempt, "stage11.source-role.receipt.json", {
        "retained_transport_fixture": positive["source_roles"],
        "generation_snapshots": positive["generation_snapshots"],
        "review_links": positive["review"], "latest": positive["latest"],
        "stage11_source_roles": "require independently trusted proposal declaration"})
    prior.put(attempt, "stage11.command-environment.receipt.json", {
        "retained_transport_fixture": positive["identity"],
        "retained_commands": positive["run_expectation"],
        "validation_argv": capture.binding(attempt / "validation.argv.json"),
        "validation_environment": capture.binding(attempt / "validation.environment.json"),
        "stage11_launch": "not inferred from validation or historical transport"})
    if not declaration_files:
        unavailable = (
            "missing independently trusted creation-time schema-1 proposal declaration "
            "byte pin for the middle-pair stage11 attention-output suffix lane")
        decision = {
            "status": "UNKNOWN", "unavailable_binding": unavailable,
            "identity_preflight_invoked": False, "dispatch_authorized": False,
            "scientific_invocations": 0, "producer_invocations": 0, "service_invocations": 0,
            "authority_root": False, "scientific_or_admission_claim": False,
            "normal_independent_review": "REQUIRED",
        }
        for member in ("proposal", "catalog", "custody", "bundle", "decision"):
            prior.put(attempt, f"stage11.{member}.receipt.json",
                      {**decision, "member": member, "authority_document_emitted": False})
        raise capture.UnavailableBinding(unavailable)

    manifest_pin, launch_pin = [capture.binding(Path(path).absolute()) for path in declaration_files]
    previous.bundle._outside_inputs(attempt, manifest_pin, launch_pin)
    origins, launch = (capture.retained_document(pin) for pin in (manifest_pin, launch_pin))
    previous.bundle._outside_inputs(attempt, origins, launch)
    prior.put(attempt, "stage11.declaration-inputs.receipt.json", {
        "caller_supplied_origins": origins, "manifest": manifest_pin, "launch": launch_pin,
        "independent_origin_trust": "caller and normal Reviewer responsibility"})
    custody_attempt, bundle_attempt = attempt / "custody", attempt / "authority-bundle"
    custody_reservation = capture.reserve_authentication_attempt(custody_attempt)
    emitted = custody.emit_custody(origins, launch, custody_attempt, custody_reservation)
    bundle_origins = custody.authority_bundle_origins(
        emitted["receipt"], origins, launch, reservation=custody_reservation)
    bundle_reservation = capture.reserve_authentication_attempt(bundle_attempt)
    materialized = previous.bundle.materialize(
        bundle_origins, launch, bundle_attempt, bundle_reservation)
    independent_origins = custody.authority_bundle_origins(
        emitted["receipt"], origins, launch, reservation=custody_reservation)
    checked = previous.bundle.validate_bundle(
        materialized["receipt"], independent_origins, launch, reservation=bundle_reservation)
    prior.put(attempt, "stage11.decision.receipt.json", {
        "custody": emitted["receipt"], "bundle": materialized["receipt"], "decision": checked,
        "service_invocations": 0, "scientific_or_admission_claim": False})
    if checked["status"] == "UNKNOWN":
        raise capture.UnavailableBinding(checked["unavailable_binding"])
    if checked["status"] != "PASS":
        raise RuntimeError(f"stage11 authority bundle rejected: {checked.get('reason')}")


def test_stage11_missing_authority_retains_every_non_emission_receipt(case, monkeypatch):
    attempt = case[0] / "missing-stage11-authority"
    attempt.mkdir()
    prior.put(attempt, "validation.argv.json", [])
