@pytest.mark.parametrize("variant", ["novel", "environment_order", "closed"])
def test_custody_to_authority_bundle(case, variant):
    if variant == "closed":
        lane = case[2]["lanes"][0]
        run = capture.retained_document(lane["capture"]["receipt"])
        case[1]["identity"] = capture.retained_document(run["results"][0]["files"][3])[
            "diagnostic_identity"]
    result, origins = produce(case)
    if variant == "environment_order":
        launch = case[3]
        launch["environment"] = dict(reversed(list(launch["environment"].items())))
        launch["command"] = capture.environment_command(launch["environment"], launch["argv"])
    bundle_origins = custody.authority_bundle_origins(
        result["receipt"], origins, case[3], reservation=result["reservation"])
    attempt = case[0] / "authority"
    reservation = capture.reserve_authentication_attempt(attempt)
    emitted = previous.bundle.materialize(bundle_origins, case[3], attempt, reservation)
    independently_derived = custody.authority_bundle_origins(
        result["receipt"], origins, case[3], reservation=result["reservation"])
    checked = previous.bundle.validate_bundle(
        emitted["receipt"], independently_derived, case[3], reservation=reservation)
    expected = "REJECTED" if variant == "closed" else "PASS"
    assert emitted["status"] == checked["status"] == expected
    assert checked["identity_preflight"]["status"] == (
        "REJECTED" if variant == "closed" else "ACCEPTED_NOVEL")
    if variant == "closed":
        assert checked["reason"] == "closed_equivalent"
    previous.assert_no_dispatch(checked)


